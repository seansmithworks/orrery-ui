// The Iris bridge: an opt-in stylesheet that points Iris's public --orrery-iris-* variables at the shared roles.
// Source: bridges/iris.json. Output: css/orrery.iris.css. src/ is not touched: Iris keeps its own literal fallbacks,
// and a page that does not load this file renders exactly as before.
import { color, dim } from './emit.mjs';

const roleName = (role) => role.split('.').pop();

/** The role's value as CSS text, for the two types a mapped role can have today. */
function roleText(t) {
  if (t.type === 'color') return color(t.value);
  if (t.type === 'dimension') return dim(t.value);
  return null;
}

// Hex case and #fff/#ffffff are the same color; lengths are compared as written.
const norm = (s) => s.trim().toLowerCase().replace(/^#([0-9a-f])([0-9a-f])([0-9a-f])$/, '#$1$1$2$2$3$3');

/** Every documented variable: the first cell of a README "Theming" table row, `--orrery-iris-*`. */
export const documentedVars = (readme) => new Set([...readme.matchAll(/^\| `(--orrery-iris-[a-z-]+)` \|/gm)].map((m) => m[1]));

/** Each literal Iris falls back to for a variable, one entry per use site: var(--orrery-iris-x, <literal>). */
function fallbacks(css, name) {
  const src = css.replace(/\/\*[\s\S]*?\*\//g, '');
  return [...src.matchAll(new RegExp(`var\\(${name}\\s*,\\s*([^(),]+)\\)`, 'g'))].map((m) => m[1]);
}

/** Failure lines: a mapped variable that is not documented, a role that does not exist, a role whose light value differs from Iris's literal. */
export function irisBridgeGate(map, lightTokens, readme, stylesCss, where) {
  const bad = [];
  const documented = documentedVars(readme);
  for (const { var: name, role } of map) {
    if (!documented.has(name)) bad.push(`iris bridge: ${name} is not a public variable documented in README.md`);
    const t = lightTokens[role];
    if (!t) { bad.push(`iris bridge: ${name} maps to ${role}, which is not a role in the source (${where})`); continue; }
    const text = roleText(t);
    const lits = fallbacks(stylesCss, name);
    if (text === null) bad.push(`iris bridge: ${name} maps to ${role}, a ${t.type}; the bridge maps colors and dimensions`);
    else if (!lits.length) bad.push(`iris bridge: ${name} has no literal fallback in src/styles.module.css to compare ${role} against`);
    else for (const lit of new Set(lits)) {
      if (norm(lit) !== norm(text)) bad.push(`iris bridge: ${name} maps to ${role} (${where}) = ${text}, but Iris falls back to ${lit.trim()} in src/styles.module.css`);
    }
  }
  return bad;
}

/** The bridge stylesheet. A role that is not defined on the page leaves its variable invalid at computed-value time, so Iris's own fallback applies. */
export function irisBridgeCss(map, brandName) {
  return [
    `/* Orrery Iris bridge, brand ${brandName}. Generated by npm run tokens:build from tokens/bridges/iris.json. Do not edit.`,
    `   OPT-IN: load after ${brandName}.css to make Iris follow the roles. Nothing loads this for you, and a page without it is unchanged.`,
    "   Only variables whose Iris default equals the role value are mapped; every other --orrery-iris-* variable keeps Iris's own literal. */",
    ':root {',
    ...map.map(({ var: name, role }) => `  ${name}: var(--${roleName(role)});`),
    '}',
  ].join('\n') + '\n';
}
