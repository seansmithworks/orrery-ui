// Tool-agnostic emitters. Input: one entry per mode, { id, name, doc, tokens }, where doc is the
// merged DTCG source and tokens maps token id -> { type, value (aliases resolved), original }.

const ext = (node) => node?.$extensions?.['com.orrery'] ?? {};
const aliasOf = (v) => (typeof v === 'string' && /^\{([^}]+)\}$/.exec(v)?.[1]) || null;
const byte = (c) => Math.round(c * 255);

export const dim = (d) => (d.value === 0 ? '0' : `${d.value}${d.unit}`);
export function color(c) {
  if (c.alpha !== undefined && c.alpha < 1) return `rgba(${c.components.map(byte).join(',')},${c.alpha})`;
  return c.hex ?? '#' + c.components.map((x) => byte(x).toString(16).padStart(2, '0')).join('');
}
const shadow = (list) => (list.length ? list.map((s) => [s.inset && 'inset', dim(s.offsetX), dim(s.offsetY), dim(s.blur), s.spread.value && dim(s.spread), color(s.color)].filter(Boolean).join(' ')).join(', ') : 'none');
const family = (names) => names.map((n) => (n.includes(' ') ? `"${n}"` : n)).join(', ');
const valueOf = (t) => ({ color: color, shadow, dimension: dim, fontFamily: family }[t.type](t.value));
// Contract values keep a direct alias as {name}, the way head.py reads them.
const contractValue = (t) => (aliasOf(t.original) ? `{${aliasOf(t.original).split('.').pop()}}` : valueOf(t));

// A group flagged $extensions.com.orrery.system is outside the Artifact contract; lib/system.mjs writes it.
// New type sizes stay out of the contract by structure: they sit in type.size and type.line-height, and contract() reads only the typography groups of doc.type.
// The other new groups (grid, breakpoint, target, elevation) stay out by the system flag.
const groups = (doc, type) => Object.entries(doc).filter(([k, g]) => !k.startsWith('$') && g.$type === type && !ext(g).system);
const leaves = (g) => Object.entries(g).filter(([k]) => !k.startsWith('$'));
const themed = (doc) => ['color', 'shadow'].flatMap((type) => groups(doc, type));

/** The Artifact contract shape read by head.py, check.mjs and the Tuner (artifact/snapshot/tokens.json). */
export function contract(modes) {
  const [first] = modes;
  const { doc } = first;
  const tok = (gname, name) => Object.fromEntries(modes.map((m) => [m.id, m.tokens[`${gname}.${name}`]]));
  const perMode = ([gname, g]) => leaves(g).map(([name, node]) => {
    const t = tok(gname, name);
    return { name, value: Object.fromEntries(modes.map((m) => [m.id, contractValue(t[m.id])])), usage: node.$description };
  });
  const out = { version: ext(doc).contract.version };
  const [colorGroup] = groups(doc, 'color');
  out.color = { themes: modes.map((m) => ({ id: m.id, name: m.name })), tokens: perMode(colorGroup), note: colorGroup[1].$description };
  out.type = {
    fonts: ext(doc.font).fonts,
    families: Object.fromEntries(leaves(doc.font).map(([k]) => [k, valueOf(first.tokens[`font.${k}`])])),
    groups: groups(doc.type, 'typography').map(([gname, g]) => ({
      name: ext(g).name,
      family: aliasOf(leaves(g)[0][1].$value.fontFamily).split('.').pop(),
      styles: leaves(g).map(([name, node]) => {
        const v = first.tokens[`type.${gname}.${name}`].value;
        const s = { name, fontSize: dim(v.fontSize), lineHeight: v.lineHeight, fontWeight: v.fontWeight };
        if (v.letterSpacing.value !== 0) s.letterSpacing = dim(v.letterSpacing);
        return { ...s, sample: ext(node).sample, usage: node.$description };
      }),
    })),
  };
  for (const [gname, g] of Object.entries(doc)) {
    if (gname.startsWith('$') || ['color', 'type', 'font'].includes(gname) || ext(g).system) continue;
    const tokens = g.$type === 'shadow' ? perMode([gname, g]) : leaves(g).map(([name, node]) => ({ name, value: valueOf(first.tokens[`${gname}.${name}`]), usage: node.$description }));
    out[gname] = { tokens, note: g.$description };
  }
  return out;
}

/** CSS custom properties, in the same selectors head.py writes them. */
export function css(modes, brandName) {
  const [first, ...rest] = modes;
  const { doc } = first;
  const v = (t) => (aliasOf(t.original) ? `var(--${aliasOf(t.original).split('.').pop()})` : valueOf(t));
  const decls = (m, indent) => themed(doc).flatMap(([gname, g]) => leaves(g).map(([name]) => `${indent}--${name}: ${v(m.tokens[`${gname}.${name}`])};`));
  const L = [`/* Orrery tokens, brand ${brandName}. Generated by npm run tokens:build from tokens/. Do not edit. */`];
  for (const url of ext(doc.font).fonts) L.push(`@import url("${url}");`);
  L.push(':root {', ...decls(first, '  '));
  for (const [gname, g] of groups(doc, 'dimension')) for (const [name] of leaves(g)) L.push(`  --${name}: ${valueOf(first.tokens[`${gname}.${name}`])};`);
  for (const [k] of leaves(doc.font)) L.push(`  --font-${k}: ${valueOf(first.tokens[`font.${k}`])};`);
  L.push(`  color-scheme: ${modes.map((m) => m.id).join(' ')};`, '}');
  for (const m of rest) {
    L.push(`@media (prefers-color-scheme: ${m.id}) {`, `  :root:not([data-theme="${first.id}"]) {`, ...decls(m, '    '), `    color-scheme: ${m.id};`, '  }', '}');
    L.push(`:root[data-theme="${m.id}"] {`, ...decls(m, '  '), `  color-scheme: ${m.id};`, '}');
  }
  L.push(`:root[data-theme="${first.id}"] { color-scheme: ${first.id}; }`);
  return L.join('\n') + '\n';
}

// ---- Swift: one file, one namespace per brand. Color (light and dark), spacing, radius, type, springs.
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const typeName = (s) => camel(s).replace(/^./, (c) => c.toUpperCase());
const num = (n) => String(n);
const rgba = (c) => `0x${color({ ...c, alpha: 1 }).slice(1)}${c.alpha !== undefined && c.alpha < 1 ? `, ${c.alpha}` : ''}`;
const WEIGHT = { 100: 'ultraLight', 200: 'thin', 300: 'light', 400: 'regular', 500: 'medium', 600: 'semibold', 700: 'bold', 800: 'heavy', 900: 'black' };

const SWIFT_HEADER = `// Orrery tokens. Generated by npm run tokens:build from tokens/. Do not edit.
import SwiftUI
#if canImport(UIKit)
import UIKit
#elseif canImport(AppKit)
import AppKit
#endif

public struct OrreryRGBA: Sendable {
    public let hex: UInt32
    public let alpha: Double
    public init(_ hex: UInt32, _ alpha: Double = 1) { self.hex = hex; self.alpha = alpha }
    var parts: (Double, Double, Double) { (Double((hex >> 16) & 0xff) / 255, Double((hex >> 8) & 0xff) / 255, Double(hex & 0xff) / 255) }
}

public extension Color {
    /// A color that follows the system appearance: \`light\` in light mode, \`dark\` in dark mode.
    init(orreryLight light: OrreryRGBA, dark: OrreryRGBA) {
        #if canImport(UIKit)
        self.init(uiColor: UIColor { traits in
            let c = traits.userInterfaceStyle == .dark ? dark : light
            return UIColor(red: c.parts.0, green: c.parts.1, blue: c.parts.2, alpha: c.alpha)
        })
        #elseif canImport(AppKit)
        self.init(nsColor: NSColor(name: nil) { appearance in
            let c = appearance.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua ? dark : light
            return NSColor(srgbRed: c.parts.0, green: c.parts.1, blue: c.parts.2, alpha: c.alpha)
        })
        #endif
    }
}

public struct OrreryTypeStyle: Sendable {
    public let family: [String]
    public let size: CGFloat
    /// Line height as a multiple of size.
    public let lineHeight: CGFloat
    public let weight: Font.Weight
    /// Tracking in em; multiply by size for points.
    public let letterSpacing: CGFloat
    public var font: Font {
        switch family.first {
        case "system-ui", "-apple-system", "sans-serif", nil: return .system(size: size, weight: weight)
        case "ui-monospace", "monospace": return .system(size: size, weight: weight, design: .monospaced)
        case let name?: return .custom(name, size: size).weight(weight)
        }
    }
}

public struct OrrerySpring: Sendable {
    public let mass: Double
    public let stiffness: Double
    public let damping: Double
    public var animation: Animation { .interpolatingSpring(mass: mass, stiffness: stiffness, damping: damping, initialVelocity: 0) }
}

public enum OrreryTokens {}
`;

export function swiftBrand(modes, brandName) {
  const [light, dark] = [modes.find((m) => m.id === 'light'), modes.find((m) => m.id === 'dark')];
  const { doc } = light;
  const L = [`public extension OrreryTokens {`, `    enum ${typeName(brandName)} {`];
  const [colorName, colorGroup] = groups(doc, 'color')[0];
  L.push('        public enum Colors {');
  for (const [name, node] of leaves(colorGroup)) {
    const id = `${colorName}.${name}`;
    L.push(`            /// ${node.$description}`, `            public static let ${camel(name)} = Color(orreryLight: .init(${rgba(light.tokens[id].value)}), dark: .init(${rgba(dark.tokens[id].value)}))`);
  }
  L.push('        }');
  for (const [gname, g] of groups(doc, 'dimension')) {
    const px = leaves(g).filter(([name]) => light.tokens[`${gname}.${name}`].value.unit === 'px');
    L.push(`        public enum ${typeName(gname)} {`);
    for (const [name] of px) L.push(`            public static let ${camel(name)}: CGFloat = ${num(light.tokens[`${gname}.${name}`].value.value)}`);
    L.push('        }');
  }
  L.push('        public enum Typography {');
  for (const [gname, g] of groups(doc.type, 'typography')) {
    for (const [name] of leaves(g)) {
      const v = light.tokens[`type.${gname}.${name}`].value;
      L.push(`            public static let ${camel(name)} = OrreryTypeStyle(family: ${JSON.stringify(v.fontFamily)}, size: ${num(v.fontSize.value)}, lineHeight: ${num(v.lineHeight)}, weight: .${WEIGHT[v.fontWeight]}, letterSpacing: ${num(v.letterSpacing.value)})`);
    }
  }
  L.push('        }', '        public enum Motion {');
  for (const [name, s] of Object.entries(ext(doc).testData.spring)) L.push(`            public static let ${camel(name)} = OrrerySpring(mass: ${num(s.mass)}, stiffness: ${num(s.stiffness)}, damping: ${num(s.damping)})`);
  L.push('        }', '    }', '}');
  return L.join('\n') + '\n';
}

export const swift = (brands) => [SWIFT_HEADER, ...brands.map((b) => swiftBrand(b.modes, b.name))].join('\n');
